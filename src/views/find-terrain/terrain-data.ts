/** WGS84, Leaflet order. GeoJSON data must be converted at the import boundary. */
export type LatLon = [latitude: number, longitude: number]

export type TerrainType = 'mountain' | 'basin' | 'river' | 'hill' | 'plain'
export interface TerrainDefinition {
  name: string
  type: TerrainType
  desc: string
  label: LatLon
  /** Independent paths: never connect separate ranges or river branches. */
  lines?: LatLon[][]
  /** Independent polygons, each containing an outer ring followed by any holes. */
  polygons?: LatLon[][][]
  representation: 'axis' | 'region' | 'river-vector'
  sources: string[]
}

/**
 * 当前 OSS 的珠江主干分成 5 段，其中一段方向相反，不能只取点数最多的单段。
 * 按已核对的南盘江—红水河—黔江—浔江—西江端点串接，排除北江、东江和三角洲支汊。
 * 用端点识别而非数组下标，允许要素重排、方向反转；仅衔接源数据不足 1 km 的端点缝隙。
 * 末端保留源数据已有范围，不另画直线延伸至海岸；OSS 换源后须重新核对这些河段。
 */
function pearlRiverMainstem(lines: LatLon[][]): LatLon[][] {
  const anchors: LatLon[] = [
    [25.878925,103.921631],[25.238,106.970459],[23.796405,109.528564],
    [23.4064,110.0893],[23.480658,111.301367],[22.575629,113.165527],
  ]
  const distanceKm = (a: LatLon, b: LatLon) => 111.2 * Math.hypot(
    a[0] - b[0], (a[1] - b[1]) * Math.cos((a[0] + b[0]) * Math.PI / 360),
  )
  const mainstem: LatLon[] = []
  for (let i = 1; i < anchors.length; i++) {
    const start = anchors[i - 1]!, end = anchors[i]!
    const matches = lines.flatMap(line => {
      const first = line[0]!, last = line[line.length - 1]!
      if (distanceKm(first, start) < 1 && distanceKm(last, end) < 1) return [line]
      if (distanceKm(last, start) < 1 && distanceKm(first, end) < 1) return [[...line].reverse()]
      return []
    })
    if (matches.length !== 1) throw new Error(`珠江干流第 ${i} 段无法识别，请核对河流数据`)
    const segment = matches[0]!, previous = mainstem[mainstem.length - 1]
    if (previous && distanceKm(previous, segment[0]!) >= 1) throw new Error('珠江干流河段不连续')
    const sharedEndpoint = previous && previous[0] === segment[0]![0] && previous[1] === segment[0]![1]
    mainstem.push(...(sharedEndpoint ? segment.slice(1) : segment))
  }
  return [mainstem]
}

/** Validate all river paths before changing the reactive quiz definitions. */
export function applyRiverGeometry(rivers: TerrainDefinition[], data: unknown) {
  const collection = data as FeatureCollection<LineString | MultiLineString, { name: string }> | null
  if (collection?.type !== 'FeatureCollection' || !Array.isArray(collection.features)) {
    throw new Error('河流数据格式无效')
  }
  const updates = rivers.map(river => {
    const matches = collection.features.filter(feature => feature?.properties?.name === river.name)
    const sourceLines: LatLon[][] = matches.flatMap(feature => {
      const geometry = feature.geometry
      if (geometry?.type !== 'MultiLineString' && geometry?.type !== 'LineString') {
        throw new Error(`${river.name}的河道类型无效`)
      }
      const paths = geometry.type === 'LineString' ? [geometry.coordinates] : geometry.coordinates
      if (!Array.isArray(paths)) throw new Error(`${river.name}的河道不完整`)
      return paths.map(line => {
        if (!Array.isArray(line) || line.length < 2) throw new Error(`${river.name}的河道不完整`)
        return line.map((position): LatLon => {
          if (!Array.isArray(position)) throw new Error(`${river.name}的坐标无效`)
          const [longitude, latitude] = position
          if (typeof longitude !== 'number' || typeof latitude !== 'number' ||
            !Number.isFinite(longitude) || !Number.isFinite(latitude) ||
            Math.abs(longitude) > 180 || Math.abs(latitude) > 90) {
            throw new Error(`${river.name}的坐标无效`)
          }
          return [latitude, longitude]
        })
      })
    })
    if (!sourceLines.length) throw new Error(`河流数据缺少：${river.name}`)
    const lines = river.name === '珠江' ? pearlRiverMainstem(sourceLines) : sourceLines
    const distance = (point: LatLon) => Math.hypot(point[0] - river.label[0], point[1] - river.label[1])
    const label = lines.flat().reduce((best, point) => distance(point) < distance(best) ? point : best)
    return { river, lines, label }
  })
  updates.forEach(({ river, lines, label }) => Object.assign(river, { lines, label }))
}

/** These separate OSS files identify the river by filename and include label points. */
export function applyNamedRiverGeometry(river: TerrainDefinition, data: unknown) {
  const collection = data as FeatureCollection | null
  if (collection?.type !== 'FeatureCollection' || !Array.isArray(collection.features)) throw new Error(`${river.name}数据格式无效`)
  const features = collection.features.filter(feature => feature?.geometry?.type !== 'Point' && feature?.geometry?.type !== 'MultiPoint')
  applyRiverGeometry([river], {
    type: 'FeatureCollection',
    features: features.map(feature => ({ ...feature, properties: { name: river.name } })),
  })
}

/** Preserve every polygon and hole from the OSS file, validating all plains before applying. */
export function applyPlainGeometry(plains: TerrainDefinition[], data: unknown) {
  const collection = data as FeatureCollection<Polygon | MultiPolygon, { NAME?: string; name?: string }> | null
  if (collection?.type !== 'FeatureCollection' || !Array.isArray(collection.features)) {
    throw new Error('平原数据格式无效')
  }
  const updates = plains.map(plain => {
    const matches = collection.features.filter(feature => (feature?.properties?.NAME ?? feature?.properties?.name) === plain.name)
    const polygons: LatLon[][][] = matches.flatMap(feature => {
      const geometry = feature.geometry
      if (geometry?.type !== 'Polygon' && geometry?.type !== 'MultiPolygon') throw new Error(`${plain.name}的面类型无效`)
      const parts = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates
      if (!Array.isArray(parts) || !parts.length) throw new Error(`${plain.name}的边界不完整`)
      return parts.map(polygon => {
        if (!Array.isArray(polygon) || !polygon.length) throw new Error(`${plain.name}的边界不完整`)
        return polygon.map(ring => {
          if (!Array.isArray(ring) || ring.length < 4) throw new Error(`${plain.name}的边界不完整`)
          const points = ring.map((position): LatLon => {
            if (!Array.isArray(position)) throw new Error(`${plain.name}的坐标无效`)
            const [longitude, latitude] = position
            if (typeof longitude !== 'number' || typeof latitude !== 'number' ||
              !Number.isFinite(longitude) || !Number.isFinite(latitude) ||
              Math.abs(longitude) > 180 || Math.abs(latitude) > 90) throw new Error(`${plain.name}的坐标无效`)
            return [latitude, longitude]
          })
          const first = points[0]!, last = points[points.length - 1]!
          if (first[0] !== last[0] || first[1] !== last[1]) throw new Error(`${plain.name}的边界未闭合`)
          return points
        })
      })
    })
    if (!polygons.length) throw new Error(`平原数据缺少：${plain.name}`)
    return { plain, polygons }
  })
  updates.forEach(({ plain, polygons }) => Object.assign(plain, { polygons }))
}

