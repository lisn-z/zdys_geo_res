/**
 * 地形范围用于课堂识图和答题判定，均为教学示意，不是测绘边界。
 * 文献用于核对整体位置、山系关系与盆缘过渡带，不提供这些顶点的测绘精度。
 * 本地轮廓经人工概化；OSS 平原也沿用教学图层，不因采用 GeoJSON 就具有测绘精度。
 * 不可将这些范围解释为精确地貌分界、行政界线或可用于面积测量的专业成果。
 */
const mountain = (name: string, desc: string, lines: LatLon[][], sources = ['geography', 'mountains']): TerrainDefinition => ({
  name, desc, type: 'mountain', lines,
  label: [...lines[0]![Math.floor(lines[0]!.length / 2)]!] as LatLon,
  representation: 'axis', sources,
})
const region = (name: string, type: 'basin' | 'hill' | 'plain', desc: string, label: LatLon, rings: LatLon[][], holesByPart: LatLon[][][] = [], sources = type === 'basin' ? ['basins'] : ['geography', 'geomorphology']): TerrainDefinition => ({
  name, type, desc, label, polygons: rings.map((ring, index) => [ring, ...(holesByPart[index] || [])]),
  representation: 'region', sources,
})

const plain = (name: string, desc: string, label: LatLon): TerrainDefinition => ({
  name, type: 'plain', desc, label, polygons: [],
  representation: 'region', sources: ['plains'],
})

